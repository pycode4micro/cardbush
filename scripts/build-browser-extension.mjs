import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const extensionRoot = fileURLToPath(new URL('../assets/plugins/chrome/extension/', import.meta.url));
const outputName = 'build-info.js';

export function extensionBuildSource(directory = extensionRoot) {
  const hash = createHash('sha256');
  // Hash executable/UI sources, not timestamps, checkout paths or this output.
  // Normalize checkout line endings so identical releases have identical IDs.
  const files = fs.readdirSync(directory).filter(name =>
    name !== outputName && /\.(?:js|html|css|json)$/.test(name)).sort();
  for (const name of files) {
    hash.update(name + '\0');
    hash.update(fs.readFileSync(path.join(directory, name), 'utf8').replace(/\r\n/g, '\n'));
    hash.update('\0');
  }
  return `// Generated by scripts/build-browser-extension.mjs; do not edit.\nglobalThis.CARDBUSH_CONNECTOR_BUILD = '${hash.digest('hex')}';\n`;
}

export function buildBrowserExtension(directory = extensionRoot, check = false) {
  const output = path.join(directory, outputName);
  const expected = extensionBuildSource(directory);
  const current = fs.existsSync(output) ? fs.readFileSync(output, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current === expected) return;
  if (check) throw new Error('Browser extension build ID is stale. Run node scripts/build-browser-extension.mjs.');
  fs.writeFileSync(output, expected);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  buildBrowserExtension(extensionRoot, process.argv.includes('--check'));
}
