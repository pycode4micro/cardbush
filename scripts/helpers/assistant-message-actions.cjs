const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

module.exports = async ({ read, until, fill, click, pause, win, directory }) => {
  await until('!!document.querySelector(".assistant-message-assistant h2")');
  const row = id => `.assistant-messages [data-message-id="${id}"]`;
  const open = async (id = 'p', selected = false) => {
    await read(`document.querySelector(${JSON.stringify(row(id))}).scrollIntoView({block:'center'});void 0`);
    await pause(180);
    await read(`(()=>{const article=document.querySelector(${JSON.stringify(row(id) + ' article')});
      if(!${selected})window.getSelection().removeAllRanges();
      article.querySelector('.assistant-text-bubble').dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,cancelable:true,clientX:innerWidth-5,clientY:innerHeight-5}));})()`);
    await until('document.querySelector(".assistant-message-menu")?.matches(":popover-open")');
  };
  const action = async key => {
    await read(`(()=>{const title=fixture.uiText(document.documentElement.lang||'zh')(${JSON.stringify(key)});Array.from(document.querySelectorAll('.assistant-message-menu > button')).find(button=>button.textContent===title).click()})()`);
  };
  await read(`Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async text=>{fixture.copied=text}}});void 0`);
  for (const theme of ['dark', 'bright']) {
    win.setSize(theme === 'dark' ? 1120 : 680, 800);
    await read(`fixture.theme(${JSON.stringify(theme)});void 0`); await pause(100);
    await open();
    assert.equal(await read('document.activeElement.hasAttribute("data-menu-reply")'), true, 'keyboard focus starts on Reply after the menu is positioned');
    const box = await read(`(()=>{const r=document.querySelector('.assistant-message-menu').getBoundingClientRect();return {left:r.left,right:r.right,bottom:r.bottom,w:innerWidth,h:innerHeight}})()`);
    assert.ok(box.left>=0&&box.right<=box.w&&box.bottom<=box.h, JSON.stringify(box));
    assert.equal(await read('document.querySelectorAll(".assistant-menu-reactions [role=menuitemradio]").length'), 6);
    fs.writeFileSync(path.join(directory, `message-menu-${theme}.png`), (await win.webContents.capturePage()).toPNG());
    await read('document.dispatchEvent(new KeyboardEvent("keydown",{key:"Escape",bubbles:true,cancelable:true}));void 0');
    await until('!document.querySelector(".assistant-message-menu")');
    assert.equal(await read('document.activeElement.matches(".assistant-message")'), true);
  }
  await open(); await action('messageBubble.copy');
  assert.equal(await read('fixture.copied'), await read('fixture.entries.find(entry=>entry.id==="p").content'));
  await fill('textarea', '保留我的草稿');
  await open(); await action('assistantMessage.reply');
  await until('!!document.querySelector(".assistant-message-quote.is-draft")');
  assert.equal(await read('document.querySelector("textarea").value'), '保留我的草稿');
  assert.equal(await read('document.activeElement===document.querySelector("textarea")'), true);
  await click('.assistant-quote-cancel');
  assert.equal(await read('document.querySelector("textarea").value'), '保留我的草稿');
  await until('!document.querySelector(".assistant-message-quote.is-draft")');
  const selection = await read(`(()=>{const n=document.querySelector(${JSON.stringify(row('p') + ' .assistant-text-bubble p')}).firstChild,r=document.createRange();r.setStart(n,0);r.setEnd(n,4);window.getSelection().removeAllRanges();window.getSelection().addRange(r);return window.getSelection().toString()})()`);
  await open('p', true); await action('assistantMessage.copySelection');
  assert.equal(await read('fixture.copied'), selection);
  await open('p', true); await action('assistantMessage.quoteSelection');
  await until('!!document.querySelector(".assistant-message-quote.is-draft")');
  assert.equal(await read('document.querySelector(".assistant-message-quote.is-draft .assistant-quote-link>span>span").textContent'), selection);
  fs.writeFileSync(path.join(directory, 'quote-draft.png'), (await win.webContents.capturePage()).toPNG());
  await click('.composer-tools .tool-chip');
  await read('Array.from(document.querySelectorAll(".composer-popover button")).find(button=>button.textContent.includes("文件和文件夹")).click();void 0');
  await until('!!document.querySelector(".composer-file-attachment")');
  await read(`fixture.management={permissions:[{permissionId:'quote-approval',toolCallId:'schedule-call',sessionId:'personal-assistant',turnId:'parent-turn',request:{reason:'Approve this scheduled report',actions:['schedule.create'],requestedCapabilityIds:['schedule.create'],targets:[{kind:'path',value:'C:/fixture/report.html'}],scope:{mode:'task_free',roots:['C:/fixture']}}}]};void 0`);
  await until('!!document.querySelector(".permission-request-card")');
  const accessoryBounds = await read(`(()=>{const p=document.querySelector('.permission-request-card').getBoundingClientRect(),q=document.querySelector('.assistant-message-quote.is-draft').getBoundingClientRect(),a=document.querySelector('.composer-attachments').getBoundingClientRect(),s=document.querySelector('.composer-surface').getBoundingClientRect();return {separate:p.bottom<=q.top&&q.bottom<=a.top&&a.bottom<=s.top,visible:p.top>=0&&s.bottom<=innerHeight}})()`);
  assert.deepEqual(accessoryBounds, { separate: true, visible: true }, 'approval, quote, attachments and text keep independent bounds');
  await click('.permission-action.deny'); await until('!document.querySelector(".permission-request-card")');
  await click('.composer-file-remove'); await until('!document.querySelector(".composer-file-attachment")');
  assert.equal(await read('document.querySelector("textarea").value'), '保留我的草稿');
  assert.equal(await read('!!document.querySelector(".assistant-message-quote.is-draft")'), true);
  await read('fixture.portal(true);void 0');
  await until('!!document.querySelector(".inspector-quick-input .assistant-message-quote.is-draft")');
  assert.equal(await read('document.querySelector("textarea").value'), '保留我的草稿');
  await read('fixture.portal(false);void 0'); await until('!!document.querySelector(".assistant-composer-dock textarea")');
  await read('fixture.holdPrepare=true;void 0');
  await click('.send-button[aria-label="发送"]');
  await until('typeof fixture.releasePrepare==="function" && !!document.querySelector(".assistant-message-user .assistant-message-quote")');
  assert.equal(await read('!!document.querySelector(".assistant-message-quote.is-draft")'), false);
  assert.equal(await read('document.querySelector("textarea").value'), '');
  await read('fixture.holdPrepare=false;fixture.releasePrepare();void 0');
  await until('fixture.sent.length===1');
  const delivered = await read('fixture.entries.at(-1)');
  assert.deepEqual(delivered.replyTo, { messageId: 'p', excerpt: selection });
  assert.equal(delivered.content, '保留我的草稿');
  await pause(450);
  fs.writeFileSync(path.join(directory, 'quote-sent.png'), (await win.webContents.capturePage()).toPNG());
  await click(row(delivered.id) + ' .assistant-quote-link');
  await until('document.querySelector("[data-message-id=p] article").dataset.quoteHighlight==="true"');
  const entriesBeforeReaction = await read('fixture.entries.length');
  await open(); await click('.assistant-menu-reactions button:first-child');
  await until('document.querySelector("[data-message-id=p] .assistant-message-reaction")?.textContent==="❤️"');
  await pause(1100);
  assert.equal(await read('fixture.entries.length'), entriesBeforeReaction);
  await open(); await click('.assistant-more-reactions');
  await until('document.querySelectorAll(".assistant-menu-reactions [role=menuitemradio]").length===12');
  await click('.assistant-extra-reactions button:first-child');
  await until('document.querySelector("[data-message-id=p] .assistant-message-reaction")?.textContent==="🎉"');
  await click(row('p') + ' .assistant-message-reaction');
  await until('!document.querySelector("[data-message-id=p] .assistant-message-reaction")');
  await read('fixture.failReact=true;void 0'); await open(); await click('.assistant-menu-reactions button:first-child');
  await until('document.querySelector(".runtime-status-banner")?.textContent.includes("表情回应未保存")');
  assert.equal(await read('!!document.querySelector("[data-message-id=p] .assistant-message-reaction")'), false);
  await read('fixture.failReact=false;fixture.failSend=true;void 0');
  await open('u'); await action('assistantMessage.reply');
  await fill('textarea', '需要重试的引用'); await click('.send-button[aria-label="发送"]');
  await until('!!document.querySelector(".assistant-message-retry")');
  assert.equal(await read('document.querySelector("textarea").value'), '需要重试的引用');
  assert.equal(await read('!!document.querySelector(".assistant-message-quote.is-draft")'), true);
  await read('fixture.failSend=false;void 0');
  await click('.send-button[aria-label="发送"]');
  await until('fixture.sent.length===2&&!document.querySelector(".assistant-message-retry")');
  assert.deepEqual(await read('fixture.entries.at(-1).replyTo'), { messageId: 'u' });
  assert.equal(await read('fixture.entries.filter(entry=>entry.content==="需要重试的引用").length'), 1);
  await open('u'); await action('assistantMessage.reply');
  await fill('textarea', '失败后保留新草稿');
  await read('fixture.holdPrepare=true;fixture.failSend=true;fixture.releasePrepare=null;void 0');
  await click('.send-button[aria-label="发送"]'); await until('typeof fixture.releasePrepare==="function"');
  await fill('textarea', '这是一条新的草稿');
  await read('fixture.holdPrepare=false;fixture.releasePrepare();void 0'); await until('!!document.querySelector(".assistant-message-retry")');
  assert.equal(await read('document.querySelector("textarea").value'), '这是一条新的草稿');
  assert.equal(await read('!!document.querySelector(".assistant-message-quote.is-draft")'), false, 'a failed send does not attach its old quote to a later draft');
  await read('fixture.failSend=false;void 0');
  await open(); await read('fixture.language("en");void 0');
  await until('document.querySelector(".assistant-message-menu")?.textContent.includes("Reply")');
  await read('document.activeElement.dispatchEvent(new KeyboardEvent("keydown",{key:"End",bubbles:true,cancelable:true}));void 0');
  assert.equal(await read('document.activeElement.textContent'), 'Copy');
  await read('document.body.dispatchEvent(new PointerEvent("pointerdown",{bubbles:true}));void 0');
  await until('!document.querySelector(".assistant-message-menu")');
  await read(`(()=>{const a=document.querySelector(${JSON.stringify(row('p') + ' article')});a.scrollIntoView({block:'center'});a.focus({preventScroll:true})})()`);
  await pause(180);
  await read(`document.activeElement.dispatchEvent(new KeyboardEvent('keydown',{key:'F10',shiftKey:true,bubbles:true,cancelable:true}));void 0`);
  await until('!!document.querySelector(".assistant-message-menu")');
  await click('.assistant-message-menu [data-menu-reply]'); await until('!!document.querySelector(".assistant-message-quote.is-draft")');
  await open();
  await read('fixture.entries=[];fixture.reactions={};fixture.generation=(fixture.generation??0)+1;window.dispatchEvent(new Event("cardbush:assistant-reset"));void 0');
  await until('!document.querySelector(".assistant-message-quote,.assistant-message-menu,.assistant-message-reaction")');
  console.log('Assistant message actions passed: bounded menu, themes/language, keyboard/dismissal, copy/selection, quote/cancel/jump, optimistic send/retry, reactions/removal/failure, portal and reset. Screenshots: '+directory);
};
