const assert = require('node:assert/strict');

module.exports = async ({ read, until, fill, click, pause, win }) => {
  const input = '.assistant-composer-dock textarea', send = '.assistant-composer-dock .send-button';
  const bubbles = text => `Array.from(document.querySelectorAll('.assistant-messages .assistant-message-user p')).filter(node=>node.textContent===${JSON.stringify(text)})`;
  await until(`!document.querySelector('${input}').readOnly`);
  await read('fixture.holdPrepare=true;void 0');
  await fill(input, '立即发送到上方');
  await read(`document.querySelector('${input}').focus();void 0`);
  win.webContents.sendInputEvent({type:'keyDown',keyCode:'Enter'});win.webContents.sendInputEvent({type:'keyUp',keyCode:'Enter'});
  await until('typeof fixture.releasePrepare==="function"');
  assert.equal(await read(`document.querySelector('${input}').value`), '', 'clear the submitted draft before configuration/admission finishes');
  assert.equal(await read(bubbles('立即发送到上方')+'.length'), 1, 'show the user message before waiting for the backend');
  assert.equal(await read(`document.querySelector('${input}').readOnly`), false, 'the next draft remains editable');
  assert.equal(await read(`document.querySelector('${send}').disabled`), true, 'pending submission cannot repeat');
  await fill(input, '下一条仍在编辑');
  await read('fixture.holdPrepare=false;fixture.holdReceipt=true;fixture.releasePrepare();void 0');
  await until('typeof fixture.releaseReceipt==="function"');await pause(1100);
  assert.equal(await read(bubbles('立即发送到上方')+'.length'), 1, 'polling reconciles the same optimistic message');
  await read('fixture.holdReceipt=false;fixture.releaseReceipt();void 0');
  await until(`!document.querySelector('${send}').disabled`);
  assert.equal(await read(`document.querySelector('${input}').value`), '下一条仍在编辑');
  await fill(input, '发送失败可恢复'); await read('fixture.holdSend=true;fixture.failSend=true;void 0');
  await click(send);await until('typeof fixture.releaseSend==="function"');
  assert.equal(await read(`document.querySelector('${input}').value`),'');
  await read('fixture.holdSend=false;fixture.releaseSend();void 0');
  await until(`document.querySelector('${input}').value==='发送失败可恢复'`);
  assert.equal(await read(bubbles('发送失败可恢复')+'.length'),1);
  await read('fixture.failSend=false;void 0'); await click(send);
  await until('fixture.sent.length===2');await pause(1100);
  assert.equal(await read(bubbles('发送失败可恢复')+'.length'),1,'retry replaces the failed message');
  assert.equal(await read('fixture.sendCalls[1].identity.id===fixture.sendCalls[2].identity.id'),true);
  await fill(input,'失败后保留新草稿');await read('fixture.holdSend=true;fixture.failSend=true;fixture.releaseSend=null;void 0');
  await click(send);await until('typeof fixture.releaseSend==="function"');await fill(input,'新草稿不能覆盖');
  await read('fixture.holdSend=false;fixture.releaseSend();void 0');
  await until('!!document.querySelector(".assistant-message-retry")');
  assert.equal(await read(`document.querySelector('${input}').value`),'新草稿不能覆盖');
  await read('fixture.failSend=false;void 0');await click('.assistant-message-retry');await until('fixture.sent.length===3');
  assert.equal(await read(`document.querySelector('${input}').value`),'新草稿不能覆盖');
  await fill(input,'回执丢失但已接收');await read('fixture.loseReceipt=true;void 0');await click(send);
  await until('fixture.sent.length===4');await until(`!document.querySelector('${send}').disabled`);
  assert.equal(await read(`document.querySelector('${input}').value`),'','accepted messages are not restored as drafts');
  assert.equal(await read(bubbles('回执丢失但已接收')+'.length'),1);
  await read('fixture.loseReceipt=false;fixture.failReadAfterAccept=true;void 0');await fill(input,'读取失败不代表发送失败');await click(send);
  await until('fixture.sent.length===5');await until(`!document.querySelector('${send}').disabled`);
  assert.equal(await read(bubbles('读取失败不代表发送失败')+'.length'),1,'keep the submitted bubble during a journal read failure');
  assert.equal(await read(`document.querySelector('${input}').value`),'');
  await read('fixture.failRead=false;fixture.failReadAfterAccept=false;void 0');await pause(1100);
  assert.equal(await read(bubbles('读取失败不代表发送失败')+'.length'),1);
  await fill(input,'重置不能复活旧消息');await read('fixture.holdSend=true;fixture.releaseSend=null;void 0');await click(send);
  await until('typeof fixture.releaseSend==="function"');
  await read('fixture.generation=(fixture.generation??0)+1;fixture.entries=[];window.dispatchEvent(new Event("cardbush:assistant-reset"));fixture.holdSend=false;fixture.releaseSend();void 0');
  await until('document.querySelectorAll(".assistant-messages .assistant-message-user").length===0');
  assert.equal(await read(`document.querySelector('${input}').value`),'');
  console.log('Assistant submission passed: instant bubble/draft clearing, delayed prepare/receipt, reconciliation, continued typing, retry, accepted/read failures and reset fencing.');
};
