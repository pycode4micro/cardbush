const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
module.exports = async ({win,BrowserWindow,openHome,openAssistant,wait,root,project,holdAudioSettings}) => {
  let current=win;
  const read=source=>current.webContents.executeJavaScript(source,true).catch(cause=>{
    throw new Error('Renderer check failed: '+source.slice(0,180),{cause});
  });
  const visible=selector=>wait(()=>read(`Boolean(document.querySelector(${JSON.stringify(selector)})?.checkVisibility())`),selector);
  const click=async selector=>{await visible(selector); await read(`document.querySelector(${JSON.stringify(selector)}).click();void 0`);};
  const menu=async()=>{await click('.profile-trigger');await visible('.profile-popover:popover-open');};
  const action=async name=>{await menu();await click('[data-profile-action='+name+']');};
  await menu();
  assert.equal(await read("!!document.querySelector('.sidebar-footer .app-center-dock')"),false);
  assert.equal(await read("(()=>{const r=document.querySelector('.profile-popover').getBoundingClientRect(),t=document.querySelector('.profile-trigger').getBoundingClientRect();return r.top>=0&&r.bottom<=t.top+1&&r.width>180})()"),true);
  await wait(()=>read("!document.querySelector('[data-profile-action=startup]').disabled"),'profile menu ready');
  fs.writeFileSync(path.join(project,'tmp','personal-profile-menu.png'),(await current.webContents.capturePage()).toPNG());
  await click('[data-profile-action=edit]');await visible('.profile-editor');
  const photo = fs.readFileSync(path.join(project,'src/features/desktop/art/fern.jpg')).toString('base64');
  await read(`(() => { const bytes=Uint8Array.from(atob(${JSON.stringify(photo)}),c=>c.charCodeAt(0));
    const files=new DataTransfer();files.items.add(new File([bytes],'photo.jpg',{type:'image/jpeg'}));
    const picker=document.querySelector('.profile-editor input[type=file]');picker.files=files.files;
    picker.dispatchEvent(new Event('change',{bubbles:true})); })()`);
  await wait(()=>read("document.querySelector('.profile-photo-preview img')?.naturalWidth===256"),'previews the decoded and cropped photo');
  await read(`for(const [selector,text] of [['[name=preferredName]','Lin'],['[name=habits]','Send short updates on Fridays.']]){
    const input=document.querySelector(selector);Object.getOwnPropertyDescriptor(Object.getPrototypeOf(input),'value').set.call(input,text);input.dispatchEvent(new Event('input',{bubbles:true}));}void 0`);
  await click('.profile-editor [type=submit]');
  await wait(()=>read("document.querySelector('.profile-trigger').textContent.includes('Lin') && !document.querySelector('.profile-editor')"),'registered profile saved');
  assert.ok(await read("document.querySelector('.profile-symbol img')?.src.startsWith('data:image/webp;base64,')"));
  await action('edit'); await visible('.profile-photo-preview img');
  fs.writeFileSync(path.join(project,'tmp','personal-profile-editor.png'),(await current.webContents.capturePage()).toPNG());
  await click('.profile-photo-remove'); await click('.profile-editor .settings-dialog-footer [type=button]');
  assert.ok(await read("!!document.querySelector('.profile-symbol img')"),'Cancel keeps the saved photo');
  await action('edit'); await visible('.profile-photo-preview img'); await click('.profile-photo-remove'); await click('.profile-editor [type=submit]');
  await wait(()=>read("!document.querySelector('.profile-editor,.profile-symbol img,.profile-avatar img')"),'saving removal restores both default avatars');
  await action('webhook');await visible('.webhook-quick-dialog');await click('.webhook-quick-dialog .settings-dialog-header button');
  await action('events');await visible('.assistant-events-dialog');await click('.assistant-events-dialog .settings-dialog-header button');
  await menu();
  await wait(()=>read("!document.querySelector('[data-profile-action=startup]').disabled"),'native startup preference');
  await click('[data-profile-action=startup]');
  await wait(()=>JSON.parse(fs.readFileSync(path.join(root,'assistant-resident.json'),'utf8')).enabled,'persist next launch');
  await action('float');
  const workspaceBounds = win.getBounds();
  const findCapsule = () => BrowserWindow.getAllWindows().find(w=>w!==win && !w.isDestroyed() && w.webContents.getURL().includes('window=assistant'));
  current=await wait(findCapsule,'separate lightweight window');
  assert.ok(win.isVisible(), 'opening the capsule keeps the original workspace visible');
  const bell = '.floating-capsule [data-action=replies]';
  await visible(bell); assert.ok(current.isAlwaysOnTop());
  await require('./floating-capsule.cjs')({current, read, click, visible, wait, project, holdAudioSettings});
  await click(bell); await visible('.capsule-replies');
  assert.ok(!await read("document.querySelector('.assistant-view')"), 'the resident renderer never mounts the old chat panel');
  current.close();
  await wait(()=>current.isDestroyed(),'release the live-switched floating renderer when idle');
  openAssistant();
  current=await wait(findCapsule,'reopen capsule from tray');
  await visible(bell); win.hide(); openHome();
  await wait(()=>win.isVisible() && current.isVisible(),'one tray click opens Home alongside the capsule');
  assert.deepEqual(win.getBounds(),workspaceBounds);
  current=win;
  await visible('[data-nav-section=chat]'); await click('[data-nav-section=chat]');
  const composer = '.main-stage .chat-panel:not(.assistant-view) textarea[data-composer-input]';
  await visible(composer);
  await read(`window.profileWorkspaceDraft=document.querySelector(${JSON.stringify(composer)});Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype,'value').set.call(profileWorkspaceDraft,'Retain this workspace draft');profileWorkspaceDraft.dispatchEvent(new Event('input',{bubbles:true}));void 0`);
  const floatSwitch = '[data-profile-action=float][role=switch]';
  await menu(); await visible(floatSwitch + '[aria-checked=true]');
  await click(floatSwitch);
  await wait(()=>!findCapsule()?.isVisible(), 'profile switch turns off an open capsule');
  await menu(); await visible(floatSwitch + '[aria-checked=false]');
  await read("document.querySelector('.profile-popover').hidePopover();void 0");
  await read("document.querySelector('[data-nav-section=assistant]').dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,cancelable:true,button:2,clientX:40,clientY:120}));void 0");
  await click('[data-sidebar-menu-item=assistant-floating]');
  const capsule = await wait(() => { const w=findCapsule(); return w?.isVisible() && w; }, 'Assistant context menu restores capsule');
  assert.ok(capsule.isAlwaysOnTop() && capsule.isVisible() && win.isVisible());
  await read('window.cardbushDesktop.voice.setCallActive(true)');
  try {
    await assert.rejects(capsule.webContents.executeJavaScript('window.cardbushDesktop.voice.setCallActive(true)'), /another CardBush window|另一个 CardBush/);
  } finally { await read('window.cardbushDesktop.voice.setCallActive(false)'); }
  assert.equal(await read("profileWorkspaceDraft.isConnected && profileWorkspaceDraft.value==='Retain this workspace draft'"),true);
  win.hide(); openHome();
  await visible('[data-desktop-page=overview]');
  assert.ok(capsule.isVisible() && win.isVisible(),'tray Home restores the workspace alongside the capsule');
  await click('[data-history-action=back]'); await visible(composer);
  assert.equal(await read(`(window.profileWorkspaceDraft=document.querySelector(${JSON.stringify(composer)})).value`),'Retain this workspace draft');
  capsule.close();
  await action('edit'); await visible('.profile-editor');
  assert.deepEqual(await read("[document.querySelector('[name=preferredName]').value, document.querySelector('[name=habits]').value]"),['Lin','Send short updates on Fridays.']);
  await click('.profile-editor .settings-dialog-header button');
  await action('settings');await visible('.settings-shell:not(.settings-inactive)');
  await visible('.settings-directory');
  assert.equal(await read("document.querySelectorAll('.sidebar').length"), 1, 'settings shares the workspace sidebar');
  assert.equal(await read("document.querySelectorAll('.settings-directory button').length"), 5);
  await read("window.settingsSidebarIdentity=document.querySelector('.desktop-shell > .sidebar');void 0");
  await wait(() => read("Math.abs(settingsSidebarIdentity.getBoundingClientRect().right - document.querySelector('.settings-shell').getBoundingClientRect().left) < 2"), 'settings aligned with the visible sidebar');
  fs.writeFileSync(path.join(project,'tmp','settings-directory-overview.png'),(await current.webContents.capturePage()).toPNG());
  await click('[data-settings-target=preferences]');
  await visible('[data-settings-section=general][aria-expanded=true]');
  await click('[data-settings-section=notifications]');
  await visible('#notification-sound-volume');
  await click('[data-settings-section=notifications]');
  assert.equal(await read("document.querySelector('#notification-sound-volume').checkVisibility()"), false);
  fs.writeFileSync(path.join(project,'tmp','settings-directory-general.png'),(await current.webContents.capturePage()).toPNG());
  await click('[data-history-action=back]'); await visible('.settings-directory');
  await click('[data-history-action=back]'); await visible(composer);
  assert.ok(await read("profileWorkspaceDraft.isConnected && profileWorkspaceDraft.value==='Retain this workspace draft'"));
  await action('settings'); await visible('.settings-directory');
  await click('[data-settings-target=connections]'); await visible('[data-settings-section=models][aria-expanded=true]');
  await click('[data-settings-overview]'); await visible('.settings-directory');
  await click('[data-nav-section=explore]'); await visible('[data-desktop-page=explore]');
  assert.ok(await read("settingsSidebarIdentity === document.querySelector('.desktop-shell > .sidebar')"));
  current.setContentSize(1180, 760);
  await visible('.desktop-shell[data-sidebar-layout=drawer].sidebar-is-collapsed');
  const rail = '.desktop-shell > .sidebar';
  await wait(()=>read("document.querySelector('.desktop-shell > .sidebar').getBoundingClientRect().width===48"),'icon rail settled');
  assert.ok(await read("!document.querySelector('.window-frame .window-sidebar-toggle') && !document.querySelector('.window-brand')"));
  assert.ok(await read("document.querySelector('.desktop-search').checkVisibility() && !document.querySelector('.desktop-search span').checkVisibility()"));
  await click('[data-nav-section=home]');
  await visible('[data-desktop-page=overview]');
  await read("window.homeLeft=document.querySelector('.main-stage').getBoundingClientRect().left;void 0");
  fs.writeFileSync(path.join(project,'tmp','sidebar-icons.png'),(await current.webContents.capturePage()).toPNG());
  await click('.window-sidebar-toggle');
  await wait(()=>read("document.querySelector('.desktop-shell > .sidebar').getBoundingClientRect().width>260 && document.querySelector('.window-brand')"),'expanded navigation');
  assert.equal(await read("document.querySelector('.main-stage').getBoundingClientRect().left"),await read('homeLeft'));
  await visible(rail+' .desktop-search span');
  fs.writeFileSync(path.join(project,'tmp','sidebar-expanded.png'),(await current.webContents.capturePage()).toPNG());
  await click('.compact-sidebar-backdrop');
  await visible('.desktop-shell.sidebar-is-collapsed');
  await click('.sidebar [data-nav-section=projects]');
  await visible('[data-desktop-page=projects]');
  await visible('.desktop-shell.sidebar-is-collapsed');
  await menu();
  await read("document.querySelector('.profile-popover:popover-open').hidePopover();void 0");
  console.log('Sidebar passed: persistent navigation, overlay geometry, profile and project shortcuts.');
  console.log('Settings directory passed: shared rail, five categories, disclosures, chronological Back, preserved draft, breadcrumb and workspace navigation.');
  console.log('Profile menu passed: real registration, webhook, events, native startup preference, lightweight and retained workspace, Assistant profile readback, settings.');
};
