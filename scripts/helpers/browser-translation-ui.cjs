const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

module.exports = async ({ window, read, waitFor, activeReady, origin, webContents, translation, calls, setMode }) => {
  const open = async path => {
    await read(`browserFixture.open({target:${JSON.stringify(origin + path)}}); void 0`);
    await waitFor(`browserFixture.activeId===${JSON.stringify(origin + path)}`);
    await activeReady();
    // DOM-ready enables page interaction before the native load has finished;
    // translation deliberately waits for the complete document.
    await waitFor('document.querySelector(".right-inspector-tab-page.active webview")?.isLoading()===false');
  };
  const button = 'document.querySelector(".right-inspector-navigation .inspector-translate-button")';
  const state = 'browserFixture.navigation[browserFixture.activeId]?.translation?.status';
  await open('/translation');
  const id = await read('document.querySelector(".right-inspector-tab-page.active webview").getWebContentsId()');
  const guest = webContents.fromId(id);
  assert.deepEqual(await translation.run(window.webContents.id + 999, { guestWebContentsId: id, action: 'translate', language: 'zh' }), { status: 'error', error: 'unavailable' });
  assert.equal(calls.length, 0, 'only the owning application may translate a guest');
  await guest.executeJavaScript('document.querySelector("input").value="Private unsent draft"; scrollTo(0,200); void 0');
  await read(`${button}.click(); void 0`);
  await waitFor(`${state}==="translated"`);
  assert.equal(await guest.executeJavaScript('document.querySelector("h1").textContent'), '中文：Overview');
  assert.equal(await guest.executeJavaScript('document.querySelector("input").value'), 'Private unsent draft');
  assert.equal(await guest.executeJavaScript('document.querySelector("code").textContent'), 'keep_code()');
  assert.equal(await guest.executeJavaScript('document.querySelector("[contenteditable]").textContent'), 'Private editable draft');
  assert.equal(await guest.executeJavaScript('typeof globalThis.__cardbushTranslation'), 'undefined', 'snapshot is isolated from page scripts');
  assert.equal(await guest.executeJavaScript('scrollY'), 200);
  assert.equal(calls[0].texts.filter(item => item.text === 'Repeated label').length, 1, 'repeated labels are sent only once');
  assert.ok(!JSON.stringify(calls).includes('Private'), 'hidden text and editable fields stay local');
  assert.equal(await guest.executeJavaScript('document.querySelectorAll("p.repeat")[1].textContent'), '中文：Repeated label');
  await guest.executeJavaScript('document.querySelector("a").click(); void 0');
  assert.equal(await guest.executeJavaScript('window.linkClicks'), 1, 'inline elements and event listeners survive');
  assert.equal(await read(`${button}.getAttribute("aria-label")`), '显示原文');
  await guest.executeJavaScript('document.querySelector("h1").textContent="Changed by page"; void 0');
  await read(`${button}.click(); void 0`);
  await waitFor(`${state}==="original"`);
  await waitFor(`document.querySelector(".right-inspector-tab-page.active webview")!==null`);
  assert.equal(await guest.executeJavaScript('document.querySelector("h1").textContent'), 'Changed by page', 'restore never overwrites newer page edits');
  assert.equal(await guest.executeJavaScript('document.querySelector("p.repeat").textContent'), 'Repeated label');

  await read('browserFixture.setLanguage("en"); void 0');
  await waitFor(`${button}.getAttribute("aria-label")==="Translate to English"`);
  await read(`${button}.click(); void 0`);
  await waitFor(`${state}==="translated"`);
  assert.equal(calls.at(-1).language, 'en');
  await read('browserFixture.setLanguage("zh"); void 0');
  await waitFor(`${state}==="original"`);
  assert.equal(await guest.executeJavaScript('document.querySelector("p.repeat").textContent'), 'Repeated label', 'language changes restore original before the next translation');

  setMode('hold');
  await read(`${button}.click(); void 0`);
  await waitFor(`${state}==="translating"`);
  await new Promise(resolve => setTimeout(resolve, 100));
  await read(`${button}.click(); void 0`);
  await waitFor(`${state}==="original"`);
  assert.ok(calls.at(-1).signal.aborted, 'clicking during translation cancels the provider request');
  await read(`${button}.click(); void 0`);
  await waitFor(`${state}==="translating"`);
  await new Promise(resolve => setTimeout(resolve, 100));
  await guest.loadURL(origin + '/translation-new');
  await activeReady();
  assert.ok(calls.at(-1).signal.aborted, 'navigation cancels the old request');
  assert.equal(await read(state), 'original');
  assert.equal(await guest.executeJavaScript('document.querySelector("#destination").textContent'), '/translation-new');

  setMode('second-batch-fails');
  await open('/translation-long');
  const long = webContents.fromId(await read('document.querySelector(".right-inspector-tab-page.active webview").getWebContentsId()'));
  await read(`${button}.click(); void 0`);
  await waitFor(`${state}==="error"`);
  assert.equal(await long.executeJavaScript('document.querySelector("p").textContent'), 'Paragraph 0', 'later failure rolls back already translated batches');
  const errorNotice = await read('document.querySelector(".right-inspector-tab-page.active .inspector-translation-notice").textContent');
  assert.ok(errorNotice.includes('翻译失败'), errorNotice + ' ' + JSON.stringify(await read('browserFixture.navigation[browserFixture.activeId]')));

  setMode('normal');
  await read(`${button}.click(); void 0`);
  await waitFor(`${state}==="translated"`);
  await waitFor('document.querySelector(".right-inspector-tab-page.active .inspector-translation-notice")===null');
  await read('browserFixture.setLayout(browserFixture.addPanel(null,browserFixture.activeId)); void 0');
  await waitFor('document.querySelector(".inspector-tile-frame .inspector-translate-button")?.getAttribute("aria-pressed")==="true"');
  await waitFor('document.querySelector(".deferred-resize-preview[data-resizing]")===null');
  await new Promise(resolve => setTimeout(resolve, 250));
  fs.writeFileSync(path.resolve('tmp/browser-translation-ui.png'), (await window.webContents.capturePage()).toPNG());
  await read('document.querySelector(".app").classList.replace("theme-bright","theme-dark"); void 0');
  await new Promise(resolve => setTimeout(resolve, 250));
  fs.writeFileSync(path.resolve('tmp/browser-translation-dark.png'), (await window.webContents.capturePage()).toPNG());
  await read('document.querySelector(".inspector-tile-frame .inspector-translate-button").click(); void 0');
  await waitFor(`${state}==="original"`);
  console.log('Browser translation: real isolated guest DOM, protected fields, deduplication, exact restore, language follow, cancellation, navigation races, rollback and tiled toolbar passed.');
};
