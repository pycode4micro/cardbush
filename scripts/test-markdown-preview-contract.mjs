import { readAppViewSources } from './helpers/app-view-sources.mjs';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';

const read = (...parts) => fs.readFileSync(path.join(process.cwd(), ...parts), 'utf8');
const app = readAppViewSources();
const styles = read('src', 'styles', 'app.css');
const main = read('electron', 'main.ts');
const textPreview = read('electron', 'textPreview.ts');
const preload = read('electron', 'preload.ts');
const desktopTypes = read('src', 'types', 'electron.d.ts');
const messageBubble = read('src', 'features', 'chatMessages', 'MessageBubble.tsx');

assert.match(app, /function isMarkdownInspectorTarget/);
assert.match(app, /markdown: MarkdownInspectorPreview/);
assert.match(app, /text: SourceInspectorPreview/);
assert.match(app, /<FilePreview\s/);
assert.doesNotMatch(app, /<header className="markdown-inspector-header">/);
assert.match(app, /<SourceSyntaxLines content=\{content\} path=\{path\} language=\{language\}/);
assert.match(app, /<MarkdownContent content=\{content\} language=\{language\}/);
assert.match(app, /MessageFileReferenceScope workspaceRoot=\{parentDirectory\(path\)\}/);
assert.match(app, /setFilePreviewRevision\(\(value\) => value \+ 1\)/);
assert.match(main, /ipcMain\.handle\('shell:read-text-preview'/);
assert.match(main, /return readTextPreviewResult\(normalizedPath\)/);
assert.match(main, /import \{ readTextPreviewResult, renderTextFilePreview \} from '\.\/textPreview'/);
assert.match(textPreview, /const maxPreviewBytes = 2 \* 1024 \* 1024/);
assert.match(textPreview, /Preview target is not a text file/);
assert.doesNotMatch(main, /zeroBytes \/ bytes\.length/);
assert.match(main, /bytes = await readHandleBytes\(handle, readableLength, range\.start\)/);
assert.match(main, /'content-length': String\(bytes\.length\)/);
assert.match(preload, /readTextPreview: \(targetPath: string\)/);
assert.match(desktopTypes, /readTextPreview: \(targetPath: string\)/);
assert.match(styles, /\.markdown-inspector-document/);
assert.match(styles, /\.source-inspector-document/);
assert.match(styles, /\.source-line-number/);
assert.match(styles, /\.inspector-preview-notice/);
assert.match(styles, /\.markdown-inspector-document \.markdown-content img/);
assert.match(messageBubble, /markdownLocalFileReference\(url, workspaceRoot\)/);
assert.match(read('src', 'features', 'chatMessages', 'fileReferences.ts'), /export function markdownLocalFileReference/);
assert.match(messageBubble, /src=\{resolvedSource\}/);

console.log('markdown inspector preview contract tests passed');
