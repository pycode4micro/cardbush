import { readFile, readdir, mkdir, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

const defaultDirectory = new URL('../src/i18n/locales/', import.meta.url);
const defaultTarget = new URL('../packages/cardbush-platform/src/i18n/generatedMessages.ts', import.meta.url);
const forms = new Set(['zero', 'one', 'two', 'few', 'many', 'other']);
const placeholders = message => [...new Set((typeof message === 'string' ? [message] : Object.values(message))
  .flatMap(text => [...text.matchAll(/\{\{|\}\}|\{([a-zA-Z][a-zA-Z0-9_]*)\}/g)].flatMap(match => match[1] ? [match[1]] : [])))].sort();

/** Also used with isolated fixture directories; never writes application preferences. */
export async function buildUiLanguagePacks({ directory = defaultDirectory, target = defaultTarget } = {}) {
  const files = (await readdir(directory)).filter(name => name.endsWith('.json')).sort();
  const packs = await Promise.all(files.map(async name => JSON.parse(await readFile(new URL(name, directory), 'utf8'))));
  const english = packs.find(pack => pack.locale === 'en');
  if (!english) throw new Error('Missing English UI language pack');
  const seen = new Set();
  for (const pack of packs) {
    const locale = Intl.getCanonicalLocales(pack.locale)[0];
    if (!locale || seen.has(locale) || typeof pack.name !== 'string' || !pack.name.trim() || !pack.messages || Array.isArray(pack.messages)) throw new Error(`Invalid UI language pack: ${pack.locale}`);
    pack.locale = locale;
    seen.add(locale);
    for (const [key, value] of Object.entries(pack.messages)) {
      if (typeof value !== 'string' && (!value || Array.isArray(value) || typeof value.other !== 'string'
        || Object.entries(value).some(([form, text]) => !forms.has(form) || typeof text !== 'string'))) throw new Error(`Invalid UI message: ${locale}/${key}`);
      if (!Object.hasOwn(english.messages, key)) throw new Error(`Unknown UI message: ${locale}/${key}`);
      if (JSON.stringify(placeholders(value)) !== JSON.stringify(placeholders(english.messages[key]))) throw new Error(`UI message variables differ: ${locale}/${key}`);
    }
  }
  // Each locale is its own module/cache boundary. Keep the synchronous catalog
  // while letting every renderer share packs without one oversized JS chunk.
  const packDirectory = new URL('./generatedPacks/', target);
  await mkdir(packDirectory, { recursive: true });
  for (const pack of packs) {
    const file = new URL(`${pack.locale}.ts`, packDirectory);
    const source = '// Generated by scripts/build-ui-language-packs.mjs.\n'
      + "import type { LanguagePack } from '../catalog.js';\n"
      + `const pack: LanguagePack = ${JSON.stringify(pack)};\nexport default pack;\n`;
    if (await readFile(file, 'utf8').catch(() => '') !== source) await writeFile(file, source);
  }
  // Only keys need literal types. Keep translated prose out of declarations.
  const source = '// Generated by scripts/build-ui-language-packs.mjs. Edit src/i18n/locales/*.json.\n'
    + "import type { LanguagePack } from './catalog.js';\n"
    + packs.map((pack, index) => `import pack${index} from './generatedPacks/${pack.locale}.js';\n`).join('')
    + `export type MessageKey = ${Object.keys(english.messages).map(key => JSON.stringify(key)).join(' | ')};\n`
    + `export const defaultPack: LanguagePack = pack${packs.indexOf(english)};\n`
    + `export const languagePacks: readonly LanguagePack[] = [defaultPack, ${packs.flatMap((pack, index) => pack === english ? [] : [`pack${index}`]).join(',')} ];\n`;
  await mkdir(new URL('./', target), { recursive: true });
  if (await readFile(target, 'utf8').catch(() => '') !== source) await writeFile(target, source);
  return { locales: packs.map(pack => pack.locale), messageCount: Object.keys(english.messages).length };
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) await buildUiLanguagePacks();
