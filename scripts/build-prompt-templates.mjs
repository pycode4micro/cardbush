import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises';

const directory = new URL('../assets/prompts/', import.meta.url);
const target = new URL('../packages/cardbush-platform/src/prompts/generatedPrompts.ts', import.meta.url);
const entries = await Promise.all((await readdir(directory)).filter(name => name.endsWith('.md')).sort()
  .map(async name => [name.slice(0, -3), (await readFile(new URL(name, directory), 'utf8')).replaceAll('\r\n', '\n').replace(/\n$/, '')]));
await mkdir(new URL('.', target), { recursive: true });
await writeFile(target, `// Generated by scripts/build-prompt-templates.mjs. Edit assets/prompts/.\nexport const prompts = ${JSON.stringify(Object.fromEntries(entries), null, 2)} as const;\n`);
