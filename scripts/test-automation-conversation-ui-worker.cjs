const assert = require('node:assert/strict');
const { join, resolve } = require('node:path');
const { app, BrowserWindow } = require('electron');
const directory = resolve(process.argv[2]);
app.disableHardwareAcceleration(); app.setPath('userData', join(directory, 'profile'));
const deadline = setTimeout(() => app.exit(1), 25000);
app.whenReady().then(async () => {
  const win = new BrowserWindow({ show: false, width: 460, height: 780, webPreferences: { sandbox: true, contextIsolation: true, nodeIntegration: false, backgroundThrottling: false, offscreen: true } });
  const read = code => win.webContents.executeJavaScript(code);
  const until = async code => { const end = Date.now()+6000; while (!await read(code)) { if(Date.now()>end)throw Error('Timed out: '+code+'; '+await read('document.body.innerText')); await new Promise(resolve=>setTimeout(resolve,25)); } };
  try {
    await win.loadFile(join(directory, 'index.html'));
    await read('document.body.style.margin="0"');
    await read('setupInbox(); showReceipt()');
    await read('document.querySelector(".automation-reminder > summary").click()');
    await read('document.querySelector(".event-result-disclosure > summary").click()');
    await until('document.querySelector(".event-result-disclosure .markdown-content strong")?.textContent==="Complete saved result"');
    assert.equal(await read('document.querySelector(".event-result-disclosure td")?.textContent'), 'Build', 'saved result tables remain readable inline');
    assert.equal(await read('document.body.innerText.includes("PRIVATE_SCHEDULER_INSTRUCTION")'),false);
    assert.equal(await read('!!document.querySelector("textarea")'),false,'history shows a result, not an execution composer');
    await read('showInbox()');
    await until('document.querySelector(".conversation-event-inbox")?.innerText.includes("已保存的提醒")');
    assert.deepEqual(await read('notified'), [], 'restored unread results are visible without replaying notifications');
    await read('holdList=true; notify()');
    await until('typeof window.releaseList==="function"');
    await read(`Object.assign(overview.jobs[0].runs[1], {status:'completed',summary:'现在该检查当前的事件了。',finishedAt:new Date().toISOString()}); notify(); releaseList()`);
    await until('document.querySelector(".conversation-event-toast")?.innerText.includes("现在该检查当前的事件了。")');
    await until('document.querySelector(".conversation-event-inbox")?.innerText.includes("现在该检查当前的事件了。")');
    assert.deepEqual(await read('notified'), [['source','new']], 'a fast isolated completion notifies its source exactly once');
    await read('document.querySelector(".conversation-event-result strong").click()');
    assert.equal(await read('calls.some(x=>x.action==="conversation" || x.action==="mark_read")'),false,'viewing results never opens or acknowledges the execution conversation');
    await read('document.querySelector(".event-toast-body").click()');
    assert.deepEqual(await read('opened'), ['source']);
    await read('showInbox("other"); notify()');
    await until('!document.querySelector(".conversation-event-inbox")');
    await read('showInbox("source",1)');
    await until('document.querySelector(".conversation-event-inbox")?.innerText.includes("现在该检查当前的事件了。")');
    assert.equal(await read('!!document.querySelector(".conversation-event-toast")'), false, 'reopening restores the card silently');
    await read('document.querySelector(".event-result-ack").click()');
    await until('document.querySelector(".conversation-event-inbox")?.innerText.includes("已保存的提醒")');
    assert.equal(await read('document.querySelector(".conversation-event-inbox").innerText.includes("现在该检查当前的事件了。")'),false);
    assert.deepEqual(await read('calls.filter(x=>x.action==="mark_read").at(-1).runIds'),['new']);
    assert.deepEqual(await read('notified'), [['source','new']]);
    console.log('Automation conversation UI passed, including live delivery to the source, delayed reads, restart, and per-run acknowledgment.');
  } finally { clearTimeout(deadline); win.destroy(); }
  app.exit(0);
}).catch(error=>{console.error(error);app.exit(1)});
