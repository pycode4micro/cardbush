import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises';

// Compile resources into both platform outputs. Installed apps never read source files.
const directory = new URL('../assets/templates/', import.meta.url);
const target = new URL('../packages/cardbush-platform/src/templates/generatedTemplates.ts', import.meta.url);
const entries = await Promise.all((await readdir(directory)).filter(name => /(?:\.html|\.js\.template)$/.test(name)).sort()
  .map(async name => [name.replace(/(?:\.html|\.js\.template)$/, ''), await readFile(new URL(name, directory), 'utf8')]));
if (new Set(entries.map(([name]) => name)).size !== entries.length) throw new Error('Duplicate template name');
await mkdir(new URL('.', target), { recursive: true });
await writeFile(target, `// Generated by scripts/build-html-templates.mjs. Edit assets/templates/.\nexport const templates = ${JSON.stringify(Object.fromEntries(entries), null, 2)} as const;\n`);
